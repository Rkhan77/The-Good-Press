-- Consent-based email notifications for The Good Press.
-- Existing and new readers begin opted out. Server-only outbox functions
-- prevent browser clients from creating or claiming delivery jobs.

create table if not exists public.notification_preferences (
  user_id uuid primary key references auth.users (id) on delete cascade,
  new_articles boolean not null default false,
  card_reset boolean not null default false,
  consented_at timestamptz,
  unsubscribed_at timestamptz,
  unsubscribe_token uuid not null default gen_random_uuid() unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notification_outbox (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('new_articles', 'card_reset')),
  user_id uuid not null references auth.users (id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  scheduled_for timestamptz not null default now(),
  status text not null default 'pending' check (status in ('pending', 'processing', 'sent', 'failed', 'skipped')),
  attempts integer not null default 0 check (attempts >= 0),
  idempotency_key text not null unique,
  last_error text,
  claimed_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notification_deliveries (
  id bigint generated by default as identity primary key,
  outbox_id bigint not null unique references public.notification_outbox (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null,
  recipient_email text not null,
  status text not null check (status in ('sent', 'failed', 'skipped')),
  detail text,
  created_at timestamptz not null default now()
);

create index if not exists notification_outbox_pending_idx
  on public.notification_outbox (scheduled_for, id)
  where status = 'pending';

create index if not exists notification_deliveries_user_created_idx
  on public.notification_deliveries (user_id, created_at desc);

create trigger notification_preferences_set_updated_at
before update on public.notification_preferences
for each row execute function public.set_updated_at();

create trigger notification_outbox_set_updated_at
before update on public.notification_outbox
for each row execute function public.set_updated_at();

create or replace function public.create_notification_preferences_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.notification_preferences (user_id)
  values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_notification_preferences on auth.users;
create trigger on_auth_user_created_notification_preferences
after insert on auth.users
for each row execute function public.create_notification_preferences_for_new_user();

insert into public.notification_preferences (user_id)
select id from auth.users
on conflict (user_id) do nothing;

alter table public.notification_preferences enable row level security;
alter table public.notification_outbox enable row level security;
alter table public.notification_deliveries enable row level security;

create policy "Readers can see their notification preferences"
on public.notification_preferences for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "Readers can update their notification preferences"
on public.notification_preferences for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

grant select on public.notification_preferences to authenticated;
grant update (new_articles, card_reset, consented_at, unsubscribed_at)
  on public.notification_preferences to authenticated;

revoke all on public.notification_outbox from anon, authenticated;
revoke all on public.notification_deliveries from anon, authenticated;

create or replace function public.queue_article_email_notifications(p_article_ids bigint[])
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  clean_ids bigint[];
  queued integer;
  batch_key text;
begin
  select coalesce(array_agg(id order by id), '{}'::bigint[])
  into clean_ids
  from public.articles
  where id = any(coalesce(p_article_ids, '{}'::bigint[]))
    and status = 'published';

  if cardinality(clean_ids) = 0 then return 0; end if;
  batch_key := md5(array_to_string(clean_ids, ','));

  insert into public.notification_outbox (kind, user_id, payload, idempotency_key)
  select
    'new_articles',
    p.user_id,
    jsonb_build_object('article_ids', to_jsonb(clean_ids)),
    'new_articles:' || p.user_id::text || ':' || batch_key
  from public.notification_preferences p
  where p.new_articles
    and p.consented_at is not null
    and p.unsubscribed_at is null
  on conflict (idempotency_key) do nothing;

  get diagnostics queued = row_count;
  return queued;
end;
$$;

revoke all on function public.queue_article_email_notifications(bigint[]) from public, anon, authenticated;
grant execute on function public.queue_article_email_notifications(bigint[]) to service_role;

create or replace function public.claim_notification_jobs(p_limit integer default 20)
returns setof public.notification_outbox
language sql
security definer
set search_path = public
as $$
  with picked as (
    select id
    from public.notification_outbox
    where (status = 'pending' or (status = 'processing' and claimed_at < now() - interval '15 minutes'))
      and scheduled_for <= now()
      and attempts < 5
    order by scheduled_for, id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 20), 100))
  )
  update public.notification_outbox o
  set status = 'processing', attempts = attempts + 1, claimed_at = now(), last_error = null
  from picked
  where o.id = picked.id
  returning o.*;
$$;

revoke all on function public.claim_notification_jobs(integer) from public, anon, authenticated;
grant execute on function public.claim_notification_jobs(integer) to service_role;

create or replace function public.record_card_read(p_article_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  u uuid := auth.uid();
  is_unlimited boolean;
  used_cards integer;
  next_feed_at timestamptz;
begin
  if u is null then raise exception 'Authentication required'; end if;
  if not exists (select 1 from articles where id = p_article_id and status = 'published') then
    raise exception 'Published article not found';
  end if;

  insert into article_reads(user_id, article_id) values (u, p_article_id)
  on conflict (user_id, article_id) do update set created_at = excluded.created_at;

  select exists(
    select 1 from subscriptions
    where user_id = u
      and status in ('active', 'trialing')
      and (current_period_end is null or current_period_end > now())
  ) into is_unlimited;

  select count(*), min(created_at) + interval '24 hours'
  into used_cards, next_feed_at
  from article_reads
  where user_id = u and created_at >= now() - interval '24 hours';

  if not is_unlimited and used_cards >= 25 and exists (
    select 1 from notification_preferences
    where user_id = u
      and card_reset
      and consented_at is not null
      and unsubscribed_at is null
  ) then
    insert into notification_outbox (kind, user_id, scheduled_for, idempotency_key)
    values (
      'card_reset',
      u,
      next_feed_at,
      'card_reset:' || u::text || ':' || extract(epoch from next_feed_at)::bigint::text
    )
    on conflict (idempotency_key) do nothing;
  end if;

  return jsonb_build_object(
    'remaining_cards', case when is_unlimited then null else greatest(0, 25 - used_cards) end,
    'next_feed_at', case when is_unlimited then null else next_feed_at end
  );
end;
$$;

grant execute on function public.record_card_read(bigint) to authenticated;

